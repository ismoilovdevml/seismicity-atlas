"""Old -> new numbers between two versions of the published site data (for docs/changes-<version>.md).

    python -I scripts/release_diff.py <old-git-rev> > docs/changes-0.5.md

Compares site/data/cells.geojson (quality codes, shown b), site/data/global.json (validation verdicts) and
site/data/manifest.json (method) at <old-git-rev> with the working tree. Read-only.
"""
import collections
import json
import statistics as st
import subprocess
import sys


def load(rev, path):
    if rev is None:
        with open(path) as f:
            return json.load(f)
    return json.loads(subprocess.run(["git", "show", f"{rev}:{path}"], check=True, capture_output=True, text=True).stdout)


def cells(rev):
    return {f["properties"]["id"]: f["properties"] for f in load(rev, "site/data/cells.geojson")["features"]}


def med(v):
    v = [x for x in v if x is not None]
    return f"{st.median(v):.3f}" if v else "–"


def main(old):
    o, n = cells(old), cells(None)
    mo, mn = load(old, "site/data/manifest.json"), load(None, "site/data/manifest.json")
    out = [f"# Changes {mo.get('version')} → {mn.get('version')}", "",
           f"Generated by `scripts/release_diff.py {old}`; old = git `{old}`, new = this release. Same data cut-off "
           f"({mn.get('data_cutoff_utc')}).", "",
           "## Method", "", "| | old | new |", "|---|---|---|",
           f"| Bootstrap replicates | {mo['method'].get('nboot')} | {mn['method'].get('nboot')} |",
           f"| Quality A | {mo['method']['quality']['A']} | {mn['method']['quality']['A']} |",
           f"| Quality B | {mo['method']['quality']['B']} | {mn['method']['quality']['B']} |", "",
           "## Cells by quality code", "", "| depth | code | old | new |", "|---|---|---|---|"]
    for d, name in (("sh", "shallow <= 70 km"), ("dp", "deeper > 70 km")):
        co = collections.Counter(p[f"{d}_q"] for p in o.values())
        cn = collections.Counter(p[f"{d}_q"] for p in n.values())
        for q in ("A", "B", "C", "insufficient"):
            out.append(f"| {name} | {q} | {co[q]} | {cn[q]} |")
    out += ["", "## Which cells moved", "",
            "Shown = quality A or B (b on the map). Median b: the new point estimate, except for newly hidden cells "
            "(masked in the new files), where it is the old one.", "",
            "| depth | group | cells | median b |", "|---|---|---|---|"]
    for d, name in (("sh", "shallow"), ("dp", "deeper")):
        shown = lambda p: p[f"{d}_q"] in ("A", "B")  # noqa: E731
        groups = {"newly shown": [i for i in o if not shown(o[i]) and shown(n[i])],
                  "newly hidden": [i for i in o if shown(o[i]) and not shown(n[i])],
                  "shown in both": [i for i in o if shown(o[i]) and shown(n[i])]}
        for g, ids in groups.items():
            src = o if g == "newly hidden" else n
            out.append(f"| {name} | {g} | {len(ids)} | {med([src[i].get(f'{d}_b') for i in ids])} |")
        moved = collections.Counter((o[i][f"{d}_q"], n[i][f"{d}_q"]) for i in o if o[i][f"{d}_q"] != n[i][f"{d}_q"])
        out.append(f"| {name} | transitions | {', '.join(f'{a}→{b} {k}' for (a, b), k in sorted(moved.items()))} | |")
    out += ["", "## Validation verdicts", ""]
    key = lambda t: t.replace(" [95 %]", "")  # noqa: E731  (0.5.0 added "[95 %]" to the Mc row labels)
    vo = {key(r["test"]): r for r in load(old, "site/data/global.json")["validation_table"]}
    vn = load(None, "site/data/global.json")["validation_table"]
    out += ["| test | data | old verdict | new verdict |", "|---|---|---|---|"]
    for r in vn:
        old_v = vo.get(key(r["test"]), {}).get("verdict", "(new row)")
        out.append(f"| {r['test']} | {r.get('data', '')} | {old_v} | {r['verdict']} |")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "HEAD")
