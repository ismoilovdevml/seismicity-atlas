"""Render an analyze() result as Markdown, JSON or a self-contained HTML page (inline SVG plot, no dependencies)."""
from __future__ import annotations

import html
import json
import math

from . import __version__


def _v(x, nd=3):
    return "–" if x is None else f"{x:.{nd}f}"


def _b_line(b: dict) -> str:
    if b.get("b") is None:
        return f"no b-value ({b['quality']})"
    s = f"{_v(b['b'])} [{_v(b['b_lo'])}, {_v(b['b_hi'])}], quality {b['quality']}, n = {b['n_above_threshold']}"
    return s if b["shown"] else s + " (withheld by the atlas rule; reference only)"


def to_markdown(res: dict) -> str:
    mc, b = res.get("mc", {}), res.get("b", {})
    L = [f"# Catalogue report: {res.get('source', '')}", "",
         f"Generated by seisatlas {__version__} (method of the Global Seismicity Atlas, https://seismicityatlas.org/).",
         "", f"*{res['disclaimer']}*", "", "## Summary", "", "| Quantity | Value |", "|---|---|",
         f"| Events used | {res['n_events']:,} |"]
    if res.get("magnitude_range"):
        L.append(f"| Magnitude range | {res['magnitude_range'][0]} to {res['magnitude_range'][1]} |")
    if res.get("time_range"):
        L.append(f"| Time range | {res['time_range'][0]} to {res['time_range'][1]} |")
    if mc:
        L.append(f"| Mc (MAXC + 0.2) [95 %] | {_v(mc.get('maxc02'), 1)} [{_v(mc.get('maxc02_lo'), 1)}, "
                 f"{_v(mc.get('maxc02_hi'), 1)}] |")
        if "mbs" in mc:
            L.append(f"| Mc, other methods | MBS {_v(mc.get('mbs'), 1)}, GFT {_v(mc.get('gft'), 1)} |")
    if b:
        L.append(f"| b-value [95 %] | {_b_line(b)} |")
        L.append(f"| b at threshold + 0.2 / + 0.4 | {_v(b.get('b_threshold_plus_0.2'))} / "
                 f"{_v(b.get('b_threshold_plus_0.4'))} |")
    if res.get("b_positive"):
        bp = res["b_positive"]
        L.append(f"| b-positive [95 %] | {_v(bp['b'])} [{_v(bp['b_lo'])}, {_v(bp['b_hi'])}], "
                 f"{bp['n_differences']} differences |")
    if res.get("magnitude_types"):
        L.append("| Magnitude types | " + ", ".join(f"{k}: {v}" for k, v in res["magnitude_types"].items()) + " |")
    L += ["", "## Warnings", ""] + ([f"- {w}" for w in res["warnings"]] or ["- None."])
    if res.get("mc_by_year"):
        L += ["", "## Mc by year (MAXC + 0.2, years with at least 50 events)", "", "| Year | Events | Mc |",
              "|---|---|---|"] + [f"| {y['year']} | {y['n']} | {_v(y['mc_maxc02'], 1)} |" for y in res["mc_by_year"]]
    s = res["settings"]
    L += ["", "## Method", "", f"- {s['method']}.", f"- Quality rule: {s['quality_rule']}.",
          f"- Bootstrap replicates: {s['nboot']}, seed {s['seed']}, magnitude bin {s['dm']}.",
          f"- Floor: {s['floor']}; period floors: {s['floor_periods']}.",
          "- Cite: Ismoilov, O. (2026). A reproducible global atlas of earthquake-catalogue completeness and b-value "
          "with uncertainty. EarthArXiv. https://doi.org/10.31223/X5X23M", ""]
    return "\n".join(L)


def to_json(res: dict) -> str:
    return json.dumps(res, indent=1, ensure_ascii=False)


def fmd_svg(res: dict, width: int = 560, height: int = 340) -> str:
    """Cumulative (dots) and per-bin (bars) counts on a log axis, the Mc line and the b-value line."""
    f = res.get("fmd")
    if not f or not f["mag"]:
        return ""
    mags, nc, cum = f["mag"], f["count"], f["cumulative"]
    pad_l, pad_r, pad_t, pad_b = 52, 16, 14, 40
    x0, x1 = min(mags) - 0.05, max(mags) + 0.05
    ymax = math.log10(max(cum)) + 0.2
    X = lambda m: pad_l + (m - x0) / (x1 - x0) * (width - pad_l - pad_r)  # noqa: E731
    Y = lambda n: pad_t + (1 - math.log10(max(n, 1)) / ymax) * (height - pad_t - pad_b)  # noqa: E731
    bw = max((width - pad_l - pad_r) / max(len(mags), 1) * 0.8, 1)
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" role="img" '
             f'aria-label="Frequency-magnitude distribution" style="max-width:100%;height:auto">',
             f'<rect width="{width}" height="{height}" fill="var(--bg,#fff)"/>']
    for k in range(0, int(ymax) + 1):
        y = Y(10 ** k)
        parts.append(f'<line x1="{pad_l}" x2="{width - pad_r}" y1="{y:.1f}" y2="{y:.1f}" stroke="var(--grid,#ddd)"/>'
                     f'<text x="{pad_l - 6}" y="{y + 4:.1f}" font-size="11" text-anchor="end" '
                     f'fill="var(--muted,#555)">{10 ** k:g}</text>')
    for m_, n_ in zip(mags, nc):
        if n_ > 0:
            parts.append(f'<rect x="{X(m_) - bw / 2:.1f}" y="{Y(n_):.1f}" width="{bw:.1f}" '
                         f'height="{Y(1) - Y(n_) + 0.01:.1f}" fill="var(--bar,#9ec5f4)"/>')
    for m_, c_ in zip(mags, cum):
        parts.append(f'<circle cx="{X(m_):.1f}" cy="{Y(c_):.1f}" r="2.6" fill="var(--fg,#222)"/>')
    mc, b = res.get("mc", {}).get("maxc02"), res.get("b", {})
    if mc is not None:
        parts.append(f'<line x1="{X(mc):.1f}" x2="{X(mc):.1f}" y1="{pad_t}" y2="{height - pad_b}" '
                     f'stroke="var(--accent,#c0392b)" stroke-dasharray="4 3"/>'
                     f'<text x="{X(mc) + 4:.1f}" y="{pad_t + 12}" font-size="11" fill="var(--accent,#c0392b)">'
                     f'Mc {mc:.1f}</text>')
        if b.get("b") is not None and b.get("n_above_threshold"):
            n0, bb = b["n_above_threshold"], b["b"]
            xa, xb = mc, max(mags)
            parts.append(f'<line x1="{X(xa):.1f}" y1="{Y(n0):.1f}" x2="{X(xb):.1f}" '
                         f'y2="{Y(n0 * 10 ** (-bb * (xb - xa))):.1f}" stroke="var(--accent,#c0392b)"/>')
    for m_ in range(math.ceil(x0), math.floor(x1) + 1):
        parts.append(f'<text x="{X(m_):.1f}" y="{height - pad_b + 16}" font-size="11" text-anchor="middle" '
                     f'fill="var(--muted,#555)">{m_}</text>')
    parts.append(f'<text x="{(pad_l + width - pad_r) / 2:.0f}" y="{height - 6}" font-size="12" text-anchor="middle" '
                 f'fill="var(--muted,#555)">Magnitude</text></svg>')
    return "".join(parts)


def to_html(res: dict) -> str:
    """Self-contained page: summary table, FMD plot, warnings, Mc by year, method. No external resources."""
    import re

    md = to_markdown(res)
    body = []
    in_table = in_list = False
    for line in md.splitlines():
        if in_list and not line.startswith("- "):
            body.append("</ul>")
            in_list = False
        esc = html.escape(line)
        esc = re.sub(r"(https?://[^\s|&]+)", r'<a href="\1">\1</a>', esc)
        if line.startswith("|"):
            cells = [c.strip() for c in esc.strip("|").split("|")]
            if set(line.replace("|", "").strip()) <= {"-"}:
                continue
            if not in_table:
                body.append("<table><thead><tr>" + "".join(f"<th>{c}</th>" for c in cells) + "</tr></thead><tbody>")
                in_table = True
            else:
                body.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
            continue
        if in_table:
            body.append("</tbody></table>")
            in_table = False
        if line.startswith("# "):
            body.append(f"<h1>{esc[2:]}</h1>")
        elif line.startswith("## "):
            body.append(f"<h2>{esc[3:]}</h2>")
            if line.startswith("## Warnings"):
                body.insert(len(body) - 1, f'<figure>{fmd_svg(res)}<figcaption>Frequency-magnitude distribution: '
                            'dots cumulative, bars per bin, dashed Mc, line the fitted b.</figcaption></figure>')
        elif line.startswith("- "):
            if not in_list:
                body.append("<ul>")
                in_list = True
            body.append(f"<li>{esc[2:]}</li>")
        elif line.startswith("*") and line.endswith("*"):
            body.append(f'<p class="note">{esc.strip("*")}</p>')
        elif line.strip():
            body.append(f"<p>{esc}</p>")
    if in_table:
        body.append("</tbody></table>")
    if in_list:
        body.append("</ul>")
    css = (":root{--bg:#fff;--fg:#1d1d1f;--muted:#555;--grid:#e3e3e3;--bar:#9ec5f4;--accent:#c0392b}"
           "@media (prefers-color-scheme:dark){:root{--bg:#141414;--fg:#eee;--muted:#aaa;--grid:#333;--bar:#2a5d93;"
           "--accent:#ff7b6b}}body{background:var(--bg);color:var(--fg);font:15px/1.5 system-ui,sans-serif;"
           "max-width:860px;margin:24px auto;padding:0 16px}table{border-collapse:collapse;width:100%;margin:8px 0}"
           "td,th{border-bottom:1px solid var(--grid);padding:6px 8px;text-align:left;vertical-align:top}"
           ".note{color:var(--muted);font-style:italic}a{color:inherit}figure{margin:16px 0}"
           "figcaption{color:var(--muted);font-size:13px}")
    return ("<!doctype html><html lang=\"en\"><head><meta charset=\"utf-8\"><meta name=\"viewport\" "
            "content=\"width=device-width,initial-scale=1\"><title>Catalogue report</title>"
            f"<style>{css}</style></head><body>{''.join(body)}</body></html>")
